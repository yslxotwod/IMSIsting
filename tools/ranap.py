#!/usr/bin/env python3
"""RANAP (TS 25.413) build and read, over the generated APER table.

This is the macro Iu-CS signalling plane: what an RNC sends an MSC, and what
an MSC sends back.  `37_femtocell` could describe it and could not put a byte
of it on a wire, because RANAP is ASN.1 over APER and nothing in this tree
carried a RANAP schema.  `tools/ranap_layout.py` is that schema, generated by
`tools/asn1gen.py --family ranap` from pycrate's RANAP namespaces.

One honest limit, stated here rather than discovered later: every RANAP
information element is an ASN.1 OPEN TYPE, and an open type is carried as a
length-prefixed octet string whose contents are the encoding of some type the
IE id names.  The table therefore carries each open type as an unconstrained
OCTET STRING and this tool takes those octets from the caller.  It does not
invent the inner type, and it does not guess which IE id means which
structure.  `ie` reads the ids pycrate does carry, from RANAP_Constants.

Regenerate the table (needs the oracle venv):
    /home/ysl/.lte-oracles/venv/bin/python tools/asn1gen.py --family ranap

The table is not certified by tools/lte-per-oracle/verify_per.py: pycrate
refuses a raw octet string for an ANY component, so the oracle cannot supply
a value for an open type and would report a hole rather than a disagreement.
The engine's own round trip (encode then decode back to the same value) is
what this tool checks, and it says so in its output.
"""

import argparse
import json
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
if _HERE not in sys.path:
    sys.path.insert(0, _HERE)

import lte_per  # noqa: E402  (the path fix-up has to come first)
import ranap_layout  # noqa: E402
from nr_rrc import Refused, _bits_of_hex, _bits_consumed  # noqa: E402

CODEC = lte_per.codec_from_module(ranap_layout)
TYPES = ranap_layout.TYPES
ROOTS = list(ranap_layout.ROOTS)
FAMILY = ranap_layout.FAMILY


def _dehex(v):
    """JSON cannot spell a byte string: {"$hex": "AABB"} is the spelling."""
    if isinstance(v, dict):
        if set(v) == {"$hex"}:
            try:
                return bytes.fromhex(v["$hex"])
            except ValueError:
                raise Refused("$hex wants an even number of hex digits")
        if set(v) == {"$choice"}:
            pair = v["$choice"]
            if not (isinstance(pair, list) and len(pair) == 2
                    and isinstance(pair[0], str)):
                raise Refused('$choice wants [alternative-name, value]')
            return (pair[0], _dehex(pair[1]))
        return {k: _dehex(x) for k, x in v.items()}
    if isinstance(v, list):
        return [_dehex(x) for x in v]
    return v


def cmd_encode(args):
    try:
        text = sys.stdin.read() if args.json == "-" else open(args.json).read()
        value = json.loads(text)
    except (OSError, ValueError) as exc:
        raise Refused("the value is not JSON: %s" % exc)
    value = _dehex(value)
    try:
        bits = CODEC.encode_bits(args.type, value)
    except lte_per.PerError as exc:
        raise Refused("the value is not a %s: %s" % (args.type, exc))
    back = CODEC.decode_bits(args.type, bits, exact=False)
    print("type\t%s" % args.type)
    print("family\t%s" % FAMILY)
    print("bits\t%d" % len(bits))
    print("hex\t%s" % hex(int(bits.ljust((len(bits) + 3) // 4 * 4, "0"), 2))[2:].zfill((len(bits) + 7) // 8 * 2).upper())
    print("read_back\t%s" % ("yes" if back == value else "no"))
    if back != value:
        raise Refused("the encoding does not decode back to the value it was "
                      "built from (a field name the table does not have is "
                      "dropped rather than refused): got %r" % (back,))
    print("limit\tthe open-type contents are the octets the caller supplied; "
          "this table does not encode any IE body")
    return 0


def cmd_decode(args):
    bits = _bits_of_hex(args.hex)
    try:
        value = CODEC.decode_bits(args.type, bits, exact=False)
    except lte_per.PerError as exc:
        raise Refused("these bits are not a %s: %s" % (args.type, exc))
    out = []
    _walk("", value, out)
    print("type\t%s" % args.type)
    print("bits\t%d" % len(bits))
    for path, v in out:
        if isinstance(v, (bytes, bytearray)):
            print("field\t%s\thex\t%s" % (path, bytes(v).hex().upper()))
        elif isinstance(v, tuple) and len(v) == 2 and isinstance(v[0], str):
            print("field\t%s\tchoice\t%s" % (path, v[0]))
        else:
            print("field\t%s\tvalue\t%s" % (path, v))
    return 0


def _walk(path, value, out, depth=0):
    if depth > 12:
        return
    if isinstance(value, dict):
        for k, v in value.items():
            _walk("%s.%s" % (path, k) if path else str(k), v, out, depth + 1)
    elif isinstance(value, list):
        for i, v in enumerate(value):
            _walk("%s[%d]" % (path, i), v, out, depth + 1)
    elif isinstance(value, tuple) and len(value) == 2 and isinstance(value[0], str):
        out.append((path, value))
        _walk("%s.%s" % (path, value[0]), value[1], out, depth + 1)
    else:
        out.append((path, value))


def cmd_ie(args):
    """IE ids from pycrate's RANAP_Constants, and nothing this tool made up."""
    try:
        from pycrate_asn1dir import RANAP
    except ImportError as exc:
        raise Refused("pycrate is not importable here (%s); the IE ids live in "
                      "pycrate's RANAP_Constants, and this tool will not print "
                      "an id it cannot read from a table" % exc)
    const = RANAP.RANAP_Constants
    rows = []
    for name in dir(const):
        if not name.startswith("id_"):
            continue
        obj = getattr(const, name)
        try:
            ident = obj.get_val()
        except Exception:
            continue
        if not isinstance(ident, int):
            continue
        pretty = name[3:]
        rows.append((ident, pretty))
    rows.sort()
    want = (args.match or "").lower()
    shown = 0
    for ident, pretty in rows:
        if want and want not in pretty.lower():
            continue
        print("ie\t%s\t%d" % (pretty, ident))
        shown += 1
    print("ies\t%d" % len(rows))
    print("matched\t%d" % shown)
    print("source\tpycrate RANAP_Constants (TS 25.413 IE id assignments)")
    return 0


def cmd_types(args):
    want = (args.match or "").lower()
    for name in ROOTS:
        print("root\t%s" % name)
    for name in sorted(TYPES):
        if want and want not in name.lower():
            continue
        print("type\t%s" % name)
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd")

    e = sub.add_parser("encode", help="encode one value (JSON) into RANAP octets")
    e.add_argument("type")
    e.add_argument("json", help="a JSON file, or - for stdin")
    e.set_defaults(func=cmd_encode)

    d = sub.add_parser("decode", help="decode RANAP octets from hex")
    d.add_argument("type")
    d.add_argument("hex")
    d.set_defaults(func=cmd_decode)

    i = sub.add_parser("ie", help="list RANAP IE ids and their names")
    i.add_argument("match", nargs="?", help="only names containing this")
    i.set_defaults(func=cmd_ie)

    t = sub.add_parser("types", help="list the roots and the table's types")
    t.add_argument("match", nargs="?")
    t.set_defaults(func=cmd_types)

    args = ap.parse_args(argv)
    if not getattr(args, "func", None):
        ap.print_help()
        return 2
    try:
        return args.func(args)
    except Refused as exc:
        print("ERROR\t%s" % exc, file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
