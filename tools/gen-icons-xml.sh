#!/usr/bin/env bash
# gen-icons-xml.sh — list every module icon in the GResource.
#
# glib-compile-resources has no glob, so each file is named. Adding an icon
# means re-running this; `tools/gen-icons-xml.sh --check` (exit 1 on drift) is
# how an icon on disk that the resource does not carry gets noticed. Missing it
# is not fatal: the launcher still installs the SVGs into the user's icon theme,
# so the icon simply is not bundled until someone re-runs the generator.
#
# The files live in icons/symbolic/ but are published inside the binary under
# icons/scalable/actions/, because that is the layout GTK's icon theme looks
# for: <search path>/<size>/<context>/<name>.svg. The GUI registers the
# resource path, so the icons resolve from the binary itself instead of from
# ~/.local/share/icons/hicolor - which needs the launcher to have run and a
# theme that the distro happens to expose - and they stay symbolic, so each
# category's accent colour still applies.
#
# The splash art is listed here too, and for the same reason: it is drawn from
# the binary before any theme, path or working directory is trustworthy. Two
# fixed files rather than a scanned directory, but the same resource.
#
# Usage: tools/gen-icons-xml.sh [--check]
set -euo pipefail
ROOT="$(cd -P "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out="$ROOT/native/resources/imsisting.gresource.xml"

generate() {
    printf '<?xml version="1.0" encoding="UTF-8"?>\n'
    printf '<!-- Generated by tools/gen-icons-xml.sh. Do not edit by hand. -->\n'
    printf '<gresources>\n'
    printf '  <gresource prefix="/com/imsisting/native">\n'
    printf '    <file>style.css</file>\n'
    # Every theme file beside it. A theme is a stylesheet the binary loads by
    # name, so it has to be in the resource or choosing it at runtime finds
    # nothing; globbing keeps a new one from needing a second edit here.
    for theme in "$ROOT"/native/resources/theme-*.css; do
        [ -f "$theme" ] || continue
        printf '    <file>%s</file>\n' "$(basename "$theme")"
    done
    printf '    <file>imsisting_splash.png</file>\n'
for f in "${ROOT}/native/resources/fonts"/*.ttf "${ROOT}/native/resources/fonts"/*.otf; do
    [[ -e "$f" ]] || continue
    printf '    <file>fonts/%s</file>\n' "$(basename "$f")"
done
    printf '    <file>imsisting_logo.png</file>\n'
    printf '    <file>imsisting_splash2.mp4</file>\n'
    printf '    <file>imsisting_splash3.mp4</file>\n'
    printf '    <file>imsisting_splash4.mp4</file>\n'
    printf '    <file>imsisting_splash5.mp4</file>\n'
    printf '    <file>imsisting_splash6.mp4</file>\n'
    # The map basemap: Natural Earth 1:110m, already flattened by
    # tools/gen-basemap.py. Compiled in for the same reason the splash is --
    # the map page paints on the first switch, before any path is trusted.
    # The GeoJSON sources stay on disk; the renderer never sees them.
    for base in land coastline countries places; do
        if [ -f "$ROOT/native/resources/basemap/$base.bin" ]; then
            printf '    <file>basemap/%s.bin</file>\n' "$base"
        fi
    done
    if [ -f "$ROOT/native/resources/basemap/places.tsv" ]; then
        printf '    <file>basemap/places.tsv</file>\n'
    fi
    ( cd "$ROOT/native/resources" && find icons/symbolic -name '*.svg' | LC_ALL=C sort ) \
        | while read -r icon; do
              printf '    <file alias="icons/scalable/actions/%s">%s</file>\n' \
                     "$(basename "$icon")" "$icon"
          done
    printf '  </gresource>\n'
    printf '</gresources>\n'
}

if [ "${1:-}" = "--check" ]; then
    tmp=$(mktemp)
    trap 'rm -f "$tmp"' EXIT
    generate > "$tmp"
    if ! diff -q "$tmp" "$out" >/dev/null; then
        printf 'gen-icons-xml: %s is out of date — re-run tools/gen-icons-xml.sh\n' "$out" >&2
        exit 1
    fi
    printf 'gen-icons-xml: up to date (%s entries)\n' "$(grep -c '<file' "$out")"
    exit 0
fi

generate > "$out"
printf 'wrote %s (%s entries)\n' "$out" "$(grep -c '<file' "$out")"
