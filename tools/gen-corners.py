#!/usr/bin/env python3
"""Derive native/resources/corners.css from the base sheet.

Square corners is a shape, and a theme is only allowed to restate colours, so
this cannot be a theme. It also cannot be the one-line sheet it started as:

  * `* { border-radius: 0 }` loses. GTK ranks a more specific selector above a
    higher provider priority, so `.sidebar row` kept its 7px corner while every
    button around it went square.
  * `!important` is not GTK CSS. The parser stops at it and logs "Junk at end of
    value for border-radius", so the declaration is dropped and the whole sheet
    does nothing -- which is exactly how this option shipped once and silently
    changed nothing.

So the sheet is derived instead of forced: every rule in style.css that sets a
radius is restated with the same selector and a zero radius. Same specificity,
loaded after the base sheet and above it, so it wins on cascade order alone.

The controls that are read by their roundness are left out of the restatement:
a switch is a circle on a track and a square one reads as a broken checkbox, a
radio dot is round because a square one is a checkbox, and a spinner is a ring.
They keep the base values because this sheet says nothing about them.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / "native" / "resources" / "style.css"
OUT = ROOT / "native" / "resources" / "corners.css"

# Selector parts whose corner is doing work: skip them entirely.
ROUND = re.compile(r"^(switch|radio|spinner)(?=$|[\s:,>])")

HEADER = """/* Square corners.
 *
 * GENERATED by tools/gen-corners.py from style.css -- edit that file or the
 * generator, never this one. Regenerate with:
 *
 *     python3 tools/gen-corners.py
 *
 * Every rule below restates a radius-bearing selector from the base sheet with
 * the radius taken out. The selectors are copied rather than invented because
 * a sheet that forces its way in cannot work here: GTK ranks specificity above
 * provider priority (so `.sidebar row` outranked a bare `*`), and GTK CSS has
 * no `!important` (the parser drops the declaration as "Junk at end of value").
 * Same selector, later provider, wins.
 *
 * Round by design and therefore absent: switch, radio, spinner. A switch is a
 * circle on a track, a radio dot is round or it is a checkbox, a spinner is a
 * ring -- squaring those makes the control unreadable rather than square.
 */
"""

RADIUS = re.compile(r"^(border-radius|border-(top|bottom)-(left|right)-radius)$")


def strip_comments(text):
    return re.sub(r"/\*.*?\*/", "", text, flags=re.S)


def rules(text):
    """Yield (selector, body, at_rule) for every flat rule, skipping at-blocks."""
    out = []
    buf = ""
    depth = 0
    at_depth = 0
    for ch in text:
        if ch == "{":
            if depth == 0:
                head = buf.strip()
                if head.startswith("@"):
                    at_depth = 1
                    buf = ""
                    depth += 1
                    continue
                sel = head
                body = ""
                buf = ""
                depth += 1
                current = [sel, body, False]
                out.append(current)
                continue
            depth += 1
            if at_depth:
                at_depth += 1
            continue
        if ch == "}":
            depth -= 1
            if depth == 0:
                buf = ""
            if at_depth:
                at_depth -= 1
            continue
        if depth == 0:
            buf += ch
        elif at_depth:
            continue
        else:
            out[-1][1] += ch
    return [(sel, body) for sel, body, _ in out]


def declarations(body):
    out = []
    for part in body.split(";"):
        if ":" not in part:
            continue
        name, value = part.split(":", 1)
        out.append((name.strip(), value.strip()))
    return out


def is_round(selector):
    for part in selector.split(","):
        part = " ".join(part.split())
        if ROUND.match(part):
            return True
    return False


def build():
    text = strip_comments(BASE.read_text(encoding="utf-8"))
    chunks = []
    seen = set()
    for selector, body in rules(text):
        decls = declarations(body)
        names = [n for n, _ in decls if RADIUS.match(n)]
        if not names:
            continue
        selector = " ".join(selector.split())
        if is_round(selector):
            continue
        key = (selector, tuple(sorted(set(names))))
        if key in seen:
            continue
        seen.add(key)
        props = "\n".join(f"    {name}: 0;" for name in sorted(set(names)))
        chunks.append(f"{selector} {{\n{props}\n}}\n")
    return HEADER + "\n" + "\n".join(chunks)


def main(argv):
    wanted = build()
    if "--check" in argv:
        have = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if have != wanted:
            print("corners.css is out of date -- run: python3 tools/gen-corners.py")
            return 1
        count = wanted.count("\n}")
        print(f"corners.css is up to date ({count} rules)")
        return 0
    OUT.write_text(wanted, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({wanted.count(chr(10) + '}')} rules)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
