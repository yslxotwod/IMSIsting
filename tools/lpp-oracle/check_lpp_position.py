#!/usr/bin/env python3
"""Differential check: our LPP position report against pycrate.

Run with the oracle interpreter, which is the only one that has pycrate::

    /home/ysl/.lte-oracles/venv/bin/python \
        tools/lpp-oracle/check_lpp_position.py [--random N]

What is compared is the whole message, bit for bit: an LPP-Message carrying a
ProvideLocationInformation built by tools/lte_asn1.py::lpp_position_message,
encoded by tools/lte_per.py from the generated table, against the same value
encoded by pycrate from TS 37.355. A table that mislays one optional bit still
encodes every fixed case it was tuned on, so the random pass is the one that
matters.

Exit status: 0 all agree, 1 a disagreement, 2 the check could not run.
"""

import argparse
import importlib.util
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.dirname(HERE)


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _bits(chunks):
    return "".join(format(c[1], "0%db" % c[2]) for c in chunks if c[2])


def pycrate_bits(root, value):
    """Encode ``value`` with pycrate and return the bit string."""
    obj = root
    obj.set_val(value)
    return _bits(obj._to_per())


# Each mutant is a one-line edit of the generated table applied at import
# time: exactly the kind of change a regeneration or a hand patch produces.
MUTANTS = [
    (
        "latitudeSign names swapped",
        "n = copy.deepcopy(TYPES['Ellipsoid_Point'])\n"
        "for c in n['comp']:\n"
        "    if c[0] == 'latitudeSign':\n"
        "        c[1]['names'] = ['south', 'north']\n"
        "TYPES['Ellipsoid_Point'] = n\n",
    ),
    (
        "longitude lower bound dropped",
        "n = copy.deepcopy(TYPES['Ellipsoid_Point'])\n"
        "for c in n['comp']:\n"
        "    if c[0] == 'degreesLongitude':\n"
        "        c[1]['lb'] = 0\n"
        "TYPES['Ellipsoid_Point'] = n\n",
    ),
]

MUTANT_TEMPLATE = """# generated by check_lpp_position.py -- a deliberately broken table
import copy
import importlib.util as _iu

_spec = _iu.spec_from_file_location("_lpp_orig", %r)
_orig = _iu.module_from_spec(_spec)
_spec.loader.exec_module(_orig)
TYPES = dict(_orig.TYPES)
ROOTS = ROOTS if (ROOTS := getattr(_orig, "ROOTS", None)) is not None else {}
UNSUPPORTED = getattr(_orig, "UNSUPPORTED", {})
%s"""


def run_negctl(tools, random_n, verbose=False):
    """Re-run this script against broken tables; each mutant must be caught."""
    import subprocess
    import tempfile

    failures = []
    table = os.path.join(tools, "lpp_layout.py")
    tmp = tempfile.mkdtemp(prefix="lpp-negctl-")
    for label, patch in MUTANTS:
        path = os.path.join(tmp, "mutant.py")
        with open(path, "w") as fh:
            fh.write(MUTANT_TEMPLATE % (table, patch))
        env = dict(os.environ, LPP_LAYOUT=path)
        proc = subprocess.run(
            [sys.executable, os.path.abspath(__file__),
             "--random", str(random_n)],
            env=env, capture_output=True, text=True)
        # A mutant counts as caught only if the differential RAN and failed.
        # A mutant that fails to import exits non-zero too, and counting that
        # would let a broken control pass as a caught defect.
        caught = proc.returncode != 0 and "RESULT\tFAIL" in proc.stdout
        if not caught:
            failures.append(
                "negctl FAIL the mutant %r was not caught by the differential "
                "(exit %d)\n  stdout: %s\n  stderr: %s"
                % (label, proc.returncode,
                   proc.stdout.strip().replace("\n", "\n          ")[:600],
                   proc.stderr.strip().splitlines()[-1:] or ""))
        elif verbose:
            print("negctl caught %s" % label)
    return failures


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--random", type=int, default=200,
                    help="random coordinate pairs to compare (default 200)")
    ap.add_argument("--seed", type=int, default=20250101)
    ap.add_argument("--negctl", action="store_true",
                    help="also run the two-sided control: broken tables must "
                         "be caught")
    args = ap.parse_args(argv)

    try:
        from pycrate_asn1dir import LPP
    except Exception as exc:                        # noqa: BLE001
        print("SKIP\tpycrate is not available: %s" % exc)
        return 2
    try:
        asn1 = _load("lte_asn1", os.path.join(TOOLS, "lte_asn1.py"))
        codec = asn1.engine("lpp")[0]
    except Exception as exc:                        # noqa: BLE001
        print("SKIP\tthe generated LPP table is not available: %s" % exc)
        return 2

    root = LPP.LPP_PDU_Definitions.LPP_Message
    failures = []
    checked = 0

    def compare(label, value, ours_bits=None):
        nonlocal checked
        try:
            theirs = pycrate_bits(root, value)
        except Exception as exc:                    # noqa: BLE001
            failures.append("%s FAIL pycrate refused the value: %s: %s"
                            % (label, type(exc).__name__, exc))
            return
        got = ours_bits
        if got is None:
            try:
                got = codec.encode_bits(asn1.LPP_ROOT, value)
            except Exception as exc:                # noqa: BLE001
                failures.append("%s FAIL our codec refused the value: %s: %s"
                                % (label, type(exc).__name__, exc))
                return
            got = "".join(str(b) for b in got) if not isinstance(got, str) else got
        checked += 1
        if got != theirs:
            at = next((i for i in range(min(len(got), len(theirs)))
                       if got[i] != theirs[i]), min(len(got), len(theirs)))
            failures.append(
                "%s FAIL encodings differ (ours %d bits, pycrate %d, first "
                "split at bit %d)\n  ours %s\n  pyc   %s"
                % (label, len(got), len(theirs), at, got, theirs))
            return
        # A matching encoding of the wrong value is still wrong: decode our
        # own bits and require the position back.
        try:
            back = codec.decode_bits(asn1.LPP_ROOT, got, exact=True)
        except Exception as exc:                    # noqa: BLE001
            failures.append("%s FAIL our decoder refused our own bits: %s: %s"
                            % (label, type(exc).__name__, exc))
            return
        if back != value:
            failures.append("%s FAIL round trip lost the value\n  in  %r\n"
                            "  out %r" % (label, value, back))

    # Fixed cases: the boundaries, both signs, and the uncertainty variant.
    # The poles and the antimeridian are where the two conversions disagree if
    # one of them treats the grid as a half-open range and the other does not.
    fixed = [
        (51.5007, -0.1246, None),
        (-33.8688, 151.2093, None),
        (0.0, 0.0, None),
        (-0.0000001, 0.0000001, None),
        (89.9999999, 179.9999999, None),
        (-89.9999999, -179.9999999, None),
        (90.0, 180.0, None),
        (-90.0, -180.0, None),
        (48.8584, 2.2945, 30),
        (37.7749, -122.4194, 127),
    ]
    for lat, lon, radius in fixed:
        value = asn1.lpp_position_message(lat, lon, radius=radius)
        compare("fixed lat=%.7f lon=%.7f radius=%s" % (lat, lon, radius), value)

    # Random differential. Coordinates are drawn on the same grid the message
    # carries, so a rounding disagreement of one step shows up as a mismatch.
    rng = random.Random(args.seed)
    for i in range(args.random):
        dlat = rng.randrange(0, asn1.LPP_LAT_STEPS)
        dlon = rng.randrange(-asn1.LPP_LON_STEPS, asn1.LPP_LON_STEPS)
        sign = rng.choice(("north", "south"))
        if rng.random() < 0.5:
            point = {"latitudeSign": sign, "degreesLatitude": dlat,
                     "degreesLongitude": dlon}
            estimate = ("ellipsoidPoint", point)
        else:
            point = {"latitudeSign": sign, "degreesLatitude": dlat,
                     "degreesLongitude": dlon,
                     "uncertainty": rng.randrange(0, 128)}
            estimate = ("ellipsoidPointWithUncertaintyCircle", point)
        value = {
            "transactionID": {"initiator": rng.choice(
                ("targetDevice", "locationServer")),
                "transactionNumber": rng.randrange(0, 256)},
            "endTransaction": bool(rng.randrange(2)),
            "sequenceNumber": rng.randrange(0, 256),
            "lpp-MessageBody": ("c1", ("provideLocationInformation", {
                "criticalExtensions": ("c1", (
                    "provideLocationInformation-r9", {
                        "commonIEsProvideLocationInformation": {
                            "locationEstimate": estimate,
                        },
                    })),
            })),
        }
        compare("random %d" % i, value)

    # The coordinate conversion has to refuse what the grid cannot carry.
    refused = 0
    for lat, lon in ((91.0, 0.0), (-91.0, 0.0), (0.0, 181.0), (0.0, -181.0)):
        try:
            asn1.lpp_encode_coord(lat, lon)
        except ValueError:
            refused += 1
    if refused != 4:
        failures.append("range FAIL the conversion accepted %d of 4 out-of-"
                        "range coordinates" % (4 - refused))

    # The builder must produce a message that carries the requested point,
    # not merely a valid message: read it back through the extractor.
    prod = asn1.lpp_position_message(51.5007, -0.1246, radius=42)
    got = asn1.lpp_read_position(prod)
    if got is None:
        failures.append("extract FAIL a position report did not read back as "
                        "one")
    else:
        if abs(got["latitude"] - 51.5007) > 1e-5 or \
                abs(got["longitude"] + 0.1246) > 1e-5:
            failures.append("extract FAIL position read back as %.7f,%.7f"
                            % (got["latitude"], got["longitude"]))
        if got["radius"] != 42 or got["shape"] != \
                "ellipsoidPointWithUncertaintyCircle":
            failures.append("extract FAIL radius/shape read back as %r/%r"
                            % (got["radius"], got["shape"]))

    # Two-sided control. A differential that cannot fail is not a check: the
    # same comparison is run against deliberately broken copies of the table
    # and has to disagree. Each mutant is a one-line edit of the generated
    # table, which is exactly the kind of edit a regeneration bug produces.
    if args.negctl:
        failures.extend(run_negctl(TOOLS, args.random))

    print("MISMATCHES\t%d" % len(failures))
    print("CASES\t%d" % checked)
    for f in failures:
        print(f)
    print("RESULT\t%s" % ("PASS" if not failures else "FAIL(%d)"
                          % len(failures)))
    return 0 if not failures else 1


if __name__ == "__main__":
    sys.exit(main())
