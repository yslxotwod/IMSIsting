#!/usr/bin/env bash
# check-gui-text.sh — fail if a CLI verb has leaked into the interface's text.
#
# A verb is how you call a module. It is not the name of a feature, and it is
# not a sentence a person should have to read to understand a button. A page
# that offers a control labelled "--tr069-audit" has failed to say what the
# control does; a help line that reads "use --apply to write the profile" has
# moved the manual onto the screen. Both are the same mistake, and the kit
# pages get it right by naming what the button does -- "Write the profile to a
# box" -- while the verb stays in the C, next to the code that passes it.
#
# So: no string literal beginning with "--" may be handed to an API that
# renders text. That is the whole check. It reads the first literal after the
# call, not every literal on the line, so a line that passes a verb into an
# argv array and then builds a label in the same breath stays legal, which is
# a shape this tree actually uses.
#
# What it cannot see: a verb that reaches a label through a variable. That
# would need the program run, and a person reading the diff is the check for
# it.
#
# Usage: tools/check-gui-text.sh [--json] [--list]
#   --list  show every rendering call this check inspected
# Exit: 0 if no rendered text is a verb, 1 otherwise.

set -uo pipefail

ROOT="$(cd -P "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="$ROOT/native/src"
jsonout=0
listall=0
for a in "$@"; do
    case "$a" in
        --json) jsonout=1 ;;
        --list) listall=1 ;;
    esac
done

[[ -d "$SRC" ]] || { echo "no $SRC" >&2; exit 2; }

# The APIs that put text on screen. Label and button constructors, their
# setters, the tooltip setters, and the string-list / drop-down feeders.
RENDER_RE='gtk_(label_new|label_set_text|label_set_markup|button_new_with_label|button_new_with_mnemonic|check_button_new_with_label|check_button_new_with_mnemonic|toggle_button_new_with_label|string_list_append|drop_down_new_from_strings|widget_set_tooltip_text|widget_set_tooltip_markup)[[:space:]]*[(]'

fail=0
n_scanned=0
declare -a offences=()

for f in "$SRC"/*.c; do
    [[ -e "$f" ]] || continue
    # Generated by tools/gen-module-index.sh from the same registries the rest
    # of the check reads; scanning it would report every module twice.
    [[ "$(basename "$f")" == "module_index.c" ]] && continue

    # A three-line window: the call, and the two lines after it. A call split
    # across lines still has its literal inside the window, and a literal that
    # appears BEFORE a call -- the common shape of an argv array followed by a
    # label on the same line -- is outside it.
    found=$(awk -v re="$RENDER_RE" '
        { line[NR] = $0 }
        END {
            for (i = 1; i <= NR; i++) {
                s = line[i]
                if (s !~ /gtk_/) continue
                w = s
                if (i + 1 <= NR) w = w "\n" line[i + 1]
                if (i + 2 <= NR) w = w "\n" line[i + 2]
                if (!match(w, re)) continue
                rest = substr(w, RSTART + RLENGTH)
                # The first literal after the call. NULL and variables are
                # not literals, so they are skipped rather than failed.
                if (!match(rest, /"[^"]*"/)) continue
                lit = substr(rest, RSTART + 1, RLENGTH - 2)
                # A verb carries a name after the dashes. A bare "--" is the
                # placeholder this tree uses for "no value yet" and is legal:
                # the status strip says "--" until a radio answers, which is
                # exactly what it should say.
                if (lit ~ /^--[a-zA-Z0-9]/) printf "%d:%s\n", i, s
            }
        }' "$f")
    rc=$?
    # A regex awk rejected must not read as "no offences found". The first
    # draft of this check used "\(" and awk turned it into "(", so it failed
    # on every file and still exited 0.
    if (( rc != 0 )); then
        echo "check-gui-text: awk failed on $(basename "$f") (rc $rc) — the check did not run" >&2
        exit 2
    fi

    n_scanned=$((n_scanned + 1))
    [[ -z "$found" ]] && continue

    while IFS= read -r hit; do
        [[ -z "$hit" ]] && continue
        offences+=("$(basename "$f"):${hit%%:*}:${hit#*:}")
        fail=$((fail + 1))
        (( jsonout )) || printf 'VERB-IN-UI  %s:%s\n' "$(basename "$f")" "${hit%%:*}"
    done <<< "$found"
done

if (( listall )) && (( jsonout == 0 )); then
    printf 'scanned %d C file(s) for rendered text built from a verb\n' "$n_scanned"
fi

if (( jsonout )); then
    printf '{"verb_in_ui":%d,"files":%d,"offences":[' "$fail" "$n_scanned"
    for i in "${!offences[@]}"; do
        (( i > 0 )) && printf ','
        printf '"%s"' "${offences[$i]}"
    done
    printf ']}\n'
else
    printf '\n'
    if (( fail == 0 )); then
        printf 'no control, label or tooltip is named after a verb\n'
        printf '  %d C file(s) scanned; every rendered verb-bearing literal is an argv entry\n' "$n_scanned"
    else
        printf '%d rendered string(s) are CLI verbs; name what the control does instead\n' "$fail"
    fi
fi

(( fail == 0 )) || exit 1
exit 0
