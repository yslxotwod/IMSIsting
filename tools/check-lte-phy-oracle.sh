#!/usr/bin/env bash
#
# Cross-check tools/lte_phy.py's downlink physical-layer stages against
# srsRAN_4G release_23_11, an independent C implementation.
#
# This check is NOT part of tools/run-selftests.sh: it needs network access,
# a C compiler and several minutes. Run it by hand when a PHY stage changes.
#
# Why it exists: the stages in tools/lte_phy.py were written from the
# specification, and the vectors carried in its selftest were computed from
# the same reading of it. A transcription can be self-consistently wrong, and
# a vector derived from it cannot catch that. srsRAN implements the same
# clauses from a separate codebase, so agreeing with it over a sweep is
# evidence rather than a restatement.
#
# What it covers: PSS and SSS (TS 36.211 6.11), layer mapping and precoding
# (TS 36.211 6.3.3), and the PBCH chain (TS 36.212 5.3.1 + TS 36.211 6.6).
#
# What it does NOT cover, stated rather than papered over: PDCCH/PCFICH/PHICH
# and the PDSCH resource mapping are not cross-checked here, because the
# drivers for them would have to drive srsRAN's DCI and REG machinery, which
# is a much larger surface. Those stages rest on their own selftest vectors.
#
# == The tolerance rule, which this script exists partly to record ==
#
# srsRAN computes PSS in single precision. Its own error against the
# closed-form definition in TS 36.211 6.11.1.1 is about 2.3e-4 -- larger than
# any reasonable "float32 noise" guess, and about 230x a 1e-6 tolerance.
# Comparing our float64 sequence to srsRAN at 1e-6 therefore FAILS against a
# correct implementation: it demands that we reproduce the oracle's rounding
# error. (This happened: a first version of the check reported three PSS
# "mismatches" that were entirely srsRAN's own error.)
#
# So PSS and SSS are checked two ways, and the two are not interchangeable:
#   1. against the closed-form definition, which is the real reference, at
#      1e-12 -- this is the check that decides correctness;
#   2. against srsRAN at a tolerance derived from srsRAN's measured error,
#      which checks that we agree with the same clause by the same route.
# Bit-exact stages (PBCH, layer mapping, precoding integers) need no
# tolerance and are compared exactly.
#
# Licensing: srsRAN_4G is AGPL-3.0. It is fetched into a temporary directory
# OUTSIDE this repository and never committed. Do not vendor it, and do not
# copy its source into this tree. The drivers under tools/lte-phy-oracle/ are
# ours; the source functions they call are compiled unmodified from upstream.
#
# Usage:  ./tools/check-lte-phy-oracle.sh [workdir]
# Exit:   0 all cases agree, 1 mismatch found, 2 could not set up the oracle.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORK="${1:-${TMPDIR:-/tmp}/imsisting-lte-phy-oracle}"
SRC="$ROOT/tools/lte-phy-oracle"
SRSRAN_TAG="release_23_11"
SRSRAN_URL="https://github.com/srsran/srsRAN_4G/archive/refs/tags/${SRSRAN_TAG}.tar.gz"

# Guard: the fetched AGPL source must never land inside the repository.
case "$(cd "$(dirname "$WORK")" && pwd)/$(basename "$WORK")" in
    "$ROOT"/*)
        echo "refusing to fetch AGPLv3 source into the repository: $WORK" >&2
        exit 2
        ;;
esac

command -v gcc >/dev/null || { echo "gcc not found" >&2; exit 2; }
command -v python3 >/dev/null || { echo "python3 not found" >&2; exit 2; }

mkdir -p "$WORK"

# --- fetch ----------------------------------------------------------------
TREE="$WORK/srsRAN_4G-${SRSRAN_TAG}"
if [ ! -d "$TREE" ]; then
    if [ ! -f "$WORK/srsran.tar.gz" ]; then
        command -v curl >/dev/null || { echo "curl not found" >&2; exit 2; }
        echo "== fetching srsRAN ${SRSRAN_TAG}"
        curl -fsSL "$SRSRAN_URL" -o "$WORK/srsran.tar.gz" || {
            echo "could not download $SRSRAN_URL" >&2; exit 2; }
    fi
    echo "== extracting"
    tar xzf "$WORK/srsran.tar.gz" -C "$WORK"
fi
[ -d "$TREE" ] || { echo "expected $TREE after extraction" >&2; exit 2; }

INC="$TREE/lib/include"
[ -d "$INC" ] || { echo "no include tree at $INC" >&2; exit 2; }

# srsran/version.h is generated by srsRAN's own cmake and is absent from the
# release tarball; lib/include/srsran/srsran.h includes it, so nothing that
# includes srsran.h -- pbch.c does -- compiles without it. config.h, the
# other generated-looking header, IS shipped, so version.h is the only one
# to fill in. Generated here rather than carried in the repo: it is srsRAN's
# file under AGPL-3.0 and must not be vendored.
GEN="$WORK/gen"
mkdir -p "$GEN/srsran"
sed -e 's/@SRSRAN_VERSION_MAJOR@/23/' \
    -e 's/@SRSRAN_VERSION_MINOR@/11/' \
    -e 's/@SRSRAN_VERSION_PATCH@/0/' \
    -e 's/@SRSRAN_VERSION_STRING@/23.11.0/' \
    "$INC/srsran/version.h.in" > "$GEN/srsran/version.h"
[ -s "$GEN/srsran/version.h" ] || { echo "could not generate version.h" >&2; exit 2; }

# --- compile --------------------------------------------------------------
# The source list per driver. Kept explicit rather than globbing lib/src,
# so that a change in what is compiled is visible in the diff.
#
# utils/debug.c is deliberately NOT in any list: it defines the same logging
# symbols as tools/lte-phy-oracle/stubs.c, and linking both is a multiple
# definition. The stubs are what upstream's debug facility is replaced with.
SYNC_SRC="sync/pss.c sync/gen_sss.c"

MIMO_SRC="mimo/layermap.c mimo/precoding.c utils/vector.c utils/vector_simd.c"

PBCH_SRC="phch/pbch.c phch/prb_dl.c phch/sequences.c fec/crc.c
          fec/convolutional/convcoder.c fec/turbo/rm_conv.c
          fec/convolutional/viterbi.c fec/convolutional/viterbi37_port.c
          scrambling/scrambling.c common/sequence.c common/phy_common.c
          modem/modem_table.c modem/mod.c modem/lte_tables.c utils/bit.c
          utils/vector.c utils/vector_simd.c
          mimo/layermap.c mimo/precoding.c"

# -ffunction-sections/-fdata-sections plus --gc-sections are load-bearing
# here, not tidiness. We want exactly one function out of sync/pss.c,
# srsran_pss_generate, but compiling the file brings its whole receiver
# along, and that half calls srsran_vec_* and srsran_dft_run_c, which live
# in sources this check does not build. Without section GC the link fails
# with about thirty undefined references that have nothing to do with what
# is being tested; with it the unused sections are dropped together with
# their relocations.
CFLAGS_COMMON="-O2 -w -ffunction-sections -fdata-sections"
LDFLAGS_GC="-Wl,--gc-sections"

build() {           # build <outdir> <driver.c> <source list...>
    local out="$1" drv="$2"; shift 2
    mkdir -p "$out"
    local objs=()
    for s in $*; do
        local o="$out/$(basename "${s%.c}").o"
        if [ ! -f "$o" ] || [ "$TREE/lib/src/phy/$s" -nt "$o" ]; then
            gcc $CFLAGS_COMMON -I"$GEN" -I"$INC" -I"$TREE/lib/src/phy" -c "$TREE/lib/src/phy/$s" -o "$o"
        fi
        objs+=("$o")
    done
    local so="$out/stubs.o"
    [ -f "$so" ] || gcc $CFLAGS_COMMON -I"$GEN" -I"$INC" -c "$SRC/stubs.c" -o "$so"
    objs+=("$so")
    local do_="$out/$(basename "${drv%.c}").o"
    gcc $CFLAGS_COMMON -I"$GEN" -I"$INC" -c "$SRC/$drv" -o "$do_"
    objs+=("$do_")
    gcc $LDFLAGS_GC "${objs[@]}" -lm -o "$out/$(basename "${drv%.c}")"
}

echo "== building oracles"
build "$WORK/oracle"      sync_dump.c $SYNC_SRC
build "$WORK/oracle/mimo" mimo_dump.c $MIMO_SRC
build "$WORK/oracle/pbch" pbch_dump.c $PBCH_SRC

# --- run ------------------------------------------------------------------
echo "== running oracles"
"$WORK/oracle/sync_dump"                 > "$WORK/oracle/srsran_sync.txt"
"$WORK/oracle/mimo/mimo_dump"            > "$WORK/oracle/mimo/dump.txt"
"$WORK/oracle/pbch/pbch_dump"            > "$WORK/oracle/pbch/dump.txt"
for f in "$WORK/oracle/srsran_sync.txt" "$WORK/oracle/mimo/dump.txt" \
         "$WORK/oracle/pbch/dump.txt"; do
    [ -s "$f" ] || { echo "oracle produced nothing: $f" >&2; exit 2; }
done

# --- compare --------------------------------------------------------------
# The comparators take the oracle directory, so they can be pointed at a
# different build without editing them.
rc=0
for cmp in cmp_sync cmp_mimo cmp_pbch; do
    echo "== $cmp"
    if ! IMSISTING_ORACLE="$WORK/oracle" python3 "$SRC/$cmp.py"; then
        rc=1
    fi
done

if [ "$rc" -eq 0 ]; then
    echo "== all downlink PHY stages agree with srsRAN ${SRSRAN_TAG}"
else
    echo "== MISMATCH: see above" >&2
fi
exit "$rc"
