#!/usr/bin/env bash
# gen-module-index.sh — harvest every module's own verbs and --info into one
# index, so documentation cannot drift from the modules.
#
# A module already knows its own verbs and semantics. The index is therefore
# generated from the modules rather than maintained by hand beside them.
#
# Emits:
#   module_index.tsv          human/tool-readable index
#   native/src/module_index.c C fragment included by the GUI
#
# Usage: tools/gen-module-index.sh [--check]
#   --check  exit 1 if the generated C file would change (CI / pre-commit)

set -uo pipefail

ROOT="$(cd -P "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MODDIR="$ROOT/modules"
OUT_TSV="$ROOT/module_index.tsv"
OUT_C="$ROOT/native/src/module_index.c"
CHECK=0
[[ "${1:-}" == "--check" ]] && CHECK=1

# Module id -> display name / category come from the GUI table so the two
# cannot disagree. The table pads columns with varying runs of spaces, so the
# three quoted fields are split by quote rather than by whitespace.
meta=$(awk '/^static const ModuleDefinition modules\[\]/,/^};/' \
        "$ROOT/native/src/main1.c" 2>/dev/null |
       grep -oE '\{ "[^"]+", *"[^"]+", *"[^"]+"' |
       awk -F'"' '{print $2"\t"$4"\t"$6}')

lookup_meta() {
    printf '%s\n' "$meta" | awk -F'\t' -v m="$1" '$1==m {print $2"\t"$3; exit}'
}

c_escape() {
    sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/	/\\t/g' | tr '\n' '~' | sed 's/~/\\n/g'
}

tmp_c=$(mktemp)
tmp_tsv=$(mktemp)
trap 'rm -f "$tmp_c" "$tmp_tsv"' EXIT

printf 'MODULE\tNAME\tCATEGORY\tVERBS\tSELFTEST\tHAS_INFO\n' > "$tmp_tsv"
{
    printf '/* Generated by tools/gen-module-index.sh — do not edit by hand. */\n'
    printf '/* Re-run the generator after adding or changing a module. */\n\n'
    printf 'typedef struct {\n'
    printf '    const char *id;\n'
    printf '    const char *name;\n'
    printf '    const char *category;\n'
    printf '    const char *verbs;\n'
    printf '    const char *info;\n'
    printf '    gboolean    has_selftest;\n'
    printf '} ModuleIndexEntry;\n\n'
    printf 'static const ModuleIndexEntry module_index[] = {\n'
} > "$tmp_c"

n=0
for f in "$MODDIR"/*.sh; do
    [[ -e "$f" ]] || continue
    id="$(basename "$f" .sh)"
    has_self=0
    grep -q -- '--selftest' "$f" && has_self=1

    # Verbs are harvested from whatever the module prints on an unknown verb.
    # Modules use at least three usage layouts, so the tokens are harvested
    # directly rather than by parsing any one of those shapes.
    usage=$(cd "$ROOT" && timeout 20 bash "$f" --__index_probe__ 2>&1 |
            grep -oE '\-\-[a-z][a-z0-9-]*' | sort -u | tr '\n' ' ')
    [[ -z "$usage" ]] && usage="(no usage text)"

    info=$(cd "$ROOT" && timeout 20 bash "$f" --info 2>/dev/null | head -c 4000)
    has_info=0
    [[ -n "$info" ]] && has_info=1
    [[ -z "$info" ]] && info="(no --info in this module)"

    mn=$(lookup_meta "$id")
    name=$(printf '%s' "$mn" | cut -f1); [[ -z "$name" ]] && name="$id"
    cat=$(printf '%s' "$mn" | cut -f2); [[ -z "$cat" ]] && cat="UNCATEGORISED"

    printf '%s\t%s\t%s\t%s\t%s\t%s\n' \
        "$id" "$name" "$cat" "$usage" "$has_self" "$has_info" >> "$tmp_tsv"
    printf '    { "%s", "%s", "%s", "%s", "%s", %s },\n' \
        "$id" \
        "$(printf '%s' "$name" | c_escape)" \
        "$(printf '%s' "$cat" | c_escape)" \
        "$(printf '%s' "$usage" | c_escape)" \
        "$(printf '%s' "$info" | c_escape | head -c 4000)" \
        "$([[ $has_self -eq 1 ]] && echo TRUE || echo FALSE)" >> "$tmp_c"
    n=$((n + 1))
done

{
    printf '};\n\n'
    printf '#define MODULE_INDEX_N ((int) G_N_ELEMENTS(module_index))\n'
} >> "$tmp_c"

if (( CHECK )); then
    if [[ -f "$OUT_C" ]] && diff -q "$tmp_c" "$OUT_C" >/dev/null 2>&1; then
        echo "module index is up to date ($n modules)"
        exit 0
    fi
    echo "module index is STALE — run tools/gen-module-index.sh" >&2
    exit 1
fi

mv "$tmp_c" "$OUT_C"
mv "$tmp_tsv" "$OUT_TSV"
chmod 644 "$OUT_C" "$OUT_TSV"
echo "indexed $n modules"
echo "  $OUT_C"
echo "  $OUT_TSV"
