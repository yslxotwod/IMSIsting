#!/usr/bin/env bash
# Referee for the hand-written manual under docs/manual/.
#
# The manual quotes verbs by name, and a hand-written page can invent one
# ("--bug-detect" was invented once and caught here, not by a reader).  This
# gate checks what no proofreader reliably catches:
#
#   1. every modules/<id>.sh the manual names exists;
#   2. every --verb on a line that names a module appears in that module's own
#      source, so a documented verb cannot be a fiction.  A line that dispatches
#      work to another machine is cut at the dispatched module id, because the
#      verb after it belongs to the module that will run over there, not here;
#   3. every fenced code block in every page is closed, and no page carries a
#      generator marker (this manual is written by hand, on purpose);
#   4. every §a.b.c reference resolves to a heading, with forward references
#      into parts not written yet reported separately as PENDING.  A manual is
#      written front to back, so a PENDING row is legal while the work is in
#      progress; --strict makes it fatal, and that is the mode the release
#      checklist runs.
#
# Usage: tools/check-manual.sh [--strict]
set -uo pipefail
ROOT="$(cd -P "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
exec python3 - "$ROOT" "$@" <<'PY'
import glob, os, re, sys
root = sys.argv[1]
strict = '--strict' in sys.argv[2:]
docs = sorted(glob.glob(os.path.join(root, 'docs', 'manual', '*.md')))
bad = 0
def fail(row, why):
    global bad
    bad += 1
    print('FAIL\t%s\t%s' % (row, why))

mod_refs = 0
verb_refs = 0
DISPATCH = re.compile(r'--dispatch\s+\S+\s+[A-Za-z0-9_]+')

for doc in docs:
    name = os.path.basename(doc)
    lines = open(doc, encoding='utf-8').read().split('\n')
    for i, line in enumerate(lines, 1):
        where = '%s:%d' % (name, i)
        m = re.search(r'modules/([A-Za-z0-9_]+)\.sh', line)
        if not m:
            continue
        mid = m.group(1)
        if not re.fullmatch(r'[0-9][a-z0-9_]*', mid):
            continue        # a placeholder in prose (modules/NN_name.sh), not a module
        path = os.path.join(root, 'modules', mid + '.sh')
        mod_refs += 1
        if not os.path.exists(path):
            fail(where, 'no such module %s' % mid)
            continue
        src = open(path, encoding='utf-8', errors='replace').read()
        head = DISPATCH.split(line)[0] if DISPATCH.search(line) else line
        for v in re.findall(r'(--[a-z][a-z0-9-]+)', head):
            verb_refs += 1
            if v not in src:
                fail(where, '%s %s is not a verb of that module' % (mid, v))

for doc in docs:
    name = os.path.basename(doc)
    text = open(doc, encoding='utf-8').read()
    fences = sum(1 for l in text.split('\n') if l.startswith('```'))
    if fences % 2:
        fail(name, 'unbalanced code fences (%d)' % fences)
    low = text.lower()
    for marker in ('<!-- generated', 'generated by tools/', 'do not edit'):
        if marker in low:
            fail(name, 'generator marker %r in a hand-written page' % marker)

headings = set()
for doc in docs:
    for l in open(doc, encoding='utf-8'):
        m = re.match(r'^#{2,3} (\d+(?:\.\d+)*)\b', l)
        if m:
            headings.add(m.group(1))

pending = 0
for doc in docs:
    name = os.path.basename(doc)
    for i, l in enumerate(open(doc, encoding='utf-8'), 1):
        for r in re.findall(r'§(\d+(?:\.\d+)+)', l):
            if r in headings:
                continue
            pending += 1
            row = '%s:%d' % (name, i)
            if strict:
                fail(row, '§%s has no such section' % r)
            else:
                print('PENDING\t%s\t§%s not written yet' % (row, r))

print('modules referenced\t%d' % mod_refs)
print('verbs referenced\t%d' % verb_refs)
print('sections\t%d' % len(headings))
print('forward references\t%d' % pending)
print('RESULT\t%s' % ('PASS' if bad == 0 else 'FAIL'))
sys.exit(0 if bad == 0 else 1)
PY
